import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";

execFileSync(process.execPath, ["--check", "app.js"], { stdio: "inherit" });
execFileSync(process.execPath, ["--check", "admin.js"], { stdio: "inherit" });
execFileSync(process.execPath, ["--check", "auth.js"], { stdio: "inherit" });
await rm("dist", { recursive: true, force: true });
await mkdir("dist", { recursive: true });
await cp("index.html", "dist/index.html");
await cp("app.js", "dist/app.js");
await cp("styles.css", "dist/styles.css");
await cp("home.css", "dist/home.css");
await cp("admin.html", "dist/admin.html");
await cp("admin.js", "dist/admin.js");
await cp("admin.css", "dist/admin.css");
await cp("admin-gate.css", "dist/admin-gate.css");
await cp("admin-gate.js", "dist/admin-gate.js");
await cp("auth.html", "dist/auth.html");
await cp("auth.js", "dist/auth.js");
const apiUrl = process.env.AUDITOR_API_URL;
await writeFile("dist/config.js", apiUrl ? `window.AUDITOR_API_URL=${JSON.stringify(apiUrl)};\n` : "window.AUDITOR_API_URL=`${window.location.protocol}//${window.location.hostname}:8000`;\n");
